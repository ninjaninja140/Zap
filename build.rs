// generates src/cmds/gen.rs from the per-command files under src/cmds/<group>/<command>.rs

use std::fs;
use std::path::Path;
use std::path::PathBuf;

// fixed display order for the registry (and therefore help output)
const GROUP_ORDER: [&str; 5] = ["install", "run", "info", "publish", "setup"];

fn main() {
    println!("cargo:rerun-if-changed=src/cmds");
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let src = gen(&root.join("src").join("cmds"));
    let out = root.join("src").join("cmds").join("gen.rs");
    // only rewrite when the content changed, so cargo doesn't rebuild every run
    if fs::read_to_string(&out).ok().as_deref() != Some(src.as_str()) {
        fs::write(&out, src).expect("failed to write src/cmds/gen.rs");
    }
}

fn gen(dir: &Path) -> String {
    // groups are the subdirectories of src/cmds, commands the .rs files inside
    // them; names starting with `_` (and gen.rs) are skipped. one group level
    // deep, nested dirs are not part of the layout
    let mut groups: Vec<(String, Vec<String>)> = Vec::new();
    for entry in fs::read_dir(dir).expect("read src/cmds") {
        let entry = entry.expect("read src/cmds entry");
        let name = entry.file_name().to_string_lossy().to_string();
        if !entry.path().is_dir() || name.starts_with('_') {
            continue;
        }
        let mut cmds: Vec<String> = Vec::new();
        for f in fs::read_dir(entry.path()).expect("read group dir") {
            let f = f.expect("read group entry");
            let fname = f.file_name().to_string_lossy().to_string();
            if !f.path().is_file() || !fname.ends_with(".rs") || fname.starts_with('_') {
                continue;
            }
            cmds.push(fname.trim_end_matches(".rs").to_string());
        }
        cmds.sort();
        groups.push((name, cmds));
    }
    // stable sort: known groups in GROUP_ORDER, unknown ones alphabetical after
    groups.sort_by(|a, b| a.0.cmp(&b.0));
    groups.sort_by_key(|(g, _)| GROUP_ORDER.iter().position(|x| x == g).unwrap_or(GROUP_ORDER.len()));

    let mut out = String::from("// generated by build.rs from the src/cmds tree, do not edit by hand\n");
    // group run + command run (etc.) are intentional layout, not inception
    out.push_str("#![allow(clippy::module_inception)]\n\n");
    for (group, cmds) in &groups {
        out.push_str(&format!("pub mod {} {{\n", group));
        for c in cmds {
            out.push_str(&format!("    #[path = \"../../{}/{}.rs\"] pub mod {};\n", group, c, c));
        }
        out.push_str("}\n\n");
    }
    out.push_str("use super::Command;\n\npub static COMMANDS: &[Command] = &[\n");
    for (group, cmds) in &groups {
        for c in cmds {
            out.push_str(&format!(
                "    Command {{ name: {}::{}::NAME, aliases: {}::{}::ALIASES, usage: {}::{}::USAGE, group: \"{}\", run: {}::{}::run }},\n",
                group, c, group, c, group, c, group, group, c
            ));
        }
    }
    out.push_str("];\n");
    out
}
