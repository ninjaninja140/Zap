// generates src/cmds/gen.rs + one standard mod.rs per group directory, from
// the per-command files under src/cmds/<group>/<command>.rs. the plain
// mod.rs form (no #[path] tricks) is deliberate: the previous generated form
// nested the commands in inline modules (`pub mod install { #[path =
// "../../install/add.rs"] ... }`) whose relative paths only resolve where the
// platform lexically normalizes `..`, windows does, posix walks every path
// component and trips over the virtual src/cmds/gen/<group>/ dir that doesn't
// exist on disk

use std::fs;
use std::path::Path;
use std::path::PathBuf;

// the api spec table drives the generated ts api (packages/api/src/api.gen.ts);
// same file the crate includes for the completeness tests
#[path = "src/api_spec.rs"]
mod api_spec;

// fixed display order for the registry (and therefore help output)
const GROUP_ORDER: [&str; 5] = ["install", "run", "info", "publish", "setup"];

// node packages whose package.json version tracks the crate (see sync_version)
const NODE_PACKAGES: [&str; 2] = ["packages/cli/package.json", "packages/api/package.json"];

fn main() {
    println!("cargo:rerun-if-changed=src/cmds");
    // a version drift in either node package must trigger a rebuild so the
    // sync below can run (rerun-if-changed paths are the only watchlist once
    // any is set)
    for pkg in NODE_PACKAGES {
        println!("cargo:rerun-if-changed={pkg}");
    }
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let cmds_dir = root.join("src").join("cmds");
    let groups = scan(&cmds_dir);
    for (group, cmds) in &groups {
        let mut body = String::from("// generated by build.rs from the src/cmds tree, do not edit by hand\n");
        // group run + command run (etc.) are intentional layout, not inception
        body.push_str("#![allow(clippy::module_inception)]\n\n");
        for c in cmds {
            body.push_str(&format!("pub mod {};\n", c));
        }
        write_if_changed(&cmds_dir.join(group).join("mod.rs"), &body);
    }
    write_if_changed(&cmds_dir.join("gen.rs"), &gen(&groups));
    // node side: package versions + the generated ts surface
    let version = std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    for pkg in NODE_PACKAGES {
        sync_version(&root.join(pkg), &version);
    }
    let api_src = root.join("packages").join("api").join("src");
    fs::create_dir_all(&api_src).expect("create packages/api/src");
    write_if_changed(&api_src.join("commands.gen.ts"), &gen_ts(&groups, &cmds_dir));
    write_if_changed(&api_src.join("api.gen.ts"), &gen_api_ts(&groups, &cmds_dir));
}

/// scan src/cmds: groups are subdirectories, commands the .rs files inside;
/// `_`-prefixed helpers, gen.rs and the generated mod.rs are not commands.
/// one group level deep, nested dirs are not part of the layout
fn scan(dir: &Path) -> Vec<(String, Vec<String>)> {
    let mut groups: Vec<(String, Vec<String>)> = Vec::new();
    for entry in fs::read_dir(dir).expect("read src/cmds") {
        let entry = entry.expect("read src/cmds entry");
        let name = entry.file_name().to_string_lossy().to_string();
        if !entry.path().is_dir() || name.starts_with('_') {
            continue;
        }
        let mut cmds: Vec<String> = Vec::new();
        for f in fs::read_dir(entry.path()).expect("read group dir") {
            let f = f.expect("read group entry");
            let fname = f.file_name().to_string_lossy().to_string();
            if !f.path().is_file() || !fname.ends_with(".rs") || fname.starts_with('_') || fname == "mod.rs" {
                continue;
            }
            cmds.push(fname.trim_end_matches(".rs").to_string());
        }
        cmds.sort();
        groups.push((name, cmds));
    }
    // stable sort: known groups in GROUP_ORDER, unknown ones alphabetical after
    groups.sort_by(|a, b| a.0.cmp(&b.0));
    groups.sort_by_key(|(g, _)| GROUP_ORDER.iter().position(|x| x == g).unwrap_or(GROUP_ORDER.len()));
    groups
}

/// gen.rs: the group modules (real mod.rs files, anchored at their own dir)
/// plus the registry; the surface stays crate::cmds::<group>::<command>
fn gen(groups: &[(String, Vec<String>)]) -> String {
    let mut out = String::from("// generated by build.rs from the src/cmds tree, do not edit by hand\n");
    for (group, _) in groups {
        // #[path] on a direct child of this file-based module resolves against
        // this file's own directory (src/cmds/), no virtual dirs involved
        out.push_str(&format!("#[path = \"{}/mod.rs\"]\npub mod {};\n\n", group, group));
    }
    out.push_str("use super::Command;\n\npub static COMMANDS: &[Command] = &[\n");
    for (group, cmds) in groups {
        for c in cmds {
            out.push_str(&format!(
                "    Command {{ name: {}::{}::NAME, aliases: {}::{}::ALIASES, usage: {}::{}::USAGE, about: {}::{}::ABOUT, example: {}::{}::EXAMPLE, group: \"{}\", run: {}::{}::run }},\n",
                group, c, group, c, group, c, group, c, group, c, group, group, c
            ));
        }
    }
    out.push_str("];\n");
    out
}

/// write only when the content differs, so cargo doesn't rebuild every run
fn write_if_changed(path: &Path, content: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(content) {
        fs::write(path, content).unwrap_or_else(|e| panic!("failed to write {}: {}", path.display(), e));
    }
}

// node package version sync

/// keep a node package's version tracking the crate; missing node side is
/// fine (packages/ is optional at build time)
fn sync_version(path: &Path, version: &str) {
    let Ok(src) = fs::read_to_string(path) else { return };
    if let Some(next) = replace_version(&src, version) {
        fs::write(path, next).unwrap_or_else(|e| panic!("failed to write {}: {}", path.display(), e));
    }
}

/// pure: swap the first `"version": "..."` value, all other formatting
/// untouched; None when the field is absent or already in sync
fn replace_version(src: &str, version: &str) -> Option<String> {
    let pat = "\"version\": \"";
    let start = src.find(pat)? + pat.len();
    let end = start + src[start..].find('"')?;
    let mut out = String::with_capacity(src.len());
    out.push_str(&src[..start]);
    out.push_str(version);
    out.push_str(&src[end..]);
    (out != src).then_some(out)
}

// packages/api/src/commands.gen.ts

/// the ts mirror of the registry: data (ZAP_VERSION/CommandMeta/COMMANDS)
/// the api re-exports. the method surface lives in api.gen.ts, driven by
/// src/api_spec.rs, that's the completeness mechanism, not this file
fn gen_ts(groups: &[(String, Vec<String>)], cmds_dir: &Path) -> String {
    let mut out = String::from("// generated by build.rs from the src/cmds tree, do not edit by hand\n\n");
    out.push_str(&format!(
        "export const ZAP_VERSION = {};\n\n",
        json_str(&std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into()))
    ));
    out.push_str("export interface CommandMeta {\n");
    out.push_str("  name: string;\n  aliases: string[];\n  usage: string;\n  about: string;\n  example: string;\n  group: string;\n}\n\n");
    out.push_str("export const COMMANDS: CommandMeta[] = [\n");
    for (group, cmds) in groups {
        for c in cmds {
            let path = cmds_dir.join(group).join(format!("{c}.rs"));
            let src = fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {}", path.display(), e));
            let name = str_const(&src, "NAME").unwrap_or_else(|| c.clone());
            out.push_str(&format!(
                "  {{ name: {}, aliases: [{}], usage: {}, about: {}, example: {}, group: {} }},\n",
                json_str(&name),
                str_list(&src, "ALIASES").iter().map(|a| json_str(a)).collect::<Vec<_>>().join(", "),
                json_str(&str_const(&src, "USAGE").unwrap_or_default()),
                json_str(&str_const(&src, "ABOUT").unwrap_or_default()),
                json_str(&str_const(&src, "EXAMPLE").unwrap_or_default()),
                json_str(group),
            ));
        }
    }
    out.push_str("];\n");
    out
}

/// pull a `pub const X: &str = "...";` literal out of a command file's source.
/// shortcut: stops at the first `";` after the opening quote, fine for the
/// registry's prose consts, would truncate on a literal `";` inside one
fn str_const(src: &str, name: &str) -> Option<String> {
    let pat = format!("pub const {name}: &str = \"");
    let rest = &src[src.find(&pat)? + pat.len()..];
    Some(unescape(&rest[..rest.find("\";")?]))
}

/// pull the string items out of a `pub const X: &[&str] = &["a", "b"];` literal
fn str_list(src: &str, name: &str) -> Vec<String> {
    let pat = format!("pub const {name}: &[&str] = &[");
    let Some(i) = src.find(&pat) else { return Vec::new() };
    let rest = &src[i + pat.len()..];
    let list = &rest[..rest.find(']').unwrap_or(rest.len())];
    // quoted items are the odd splits: `&["a", "b"]` → ["", "a", ", ", "b", ...]
    list.split('"')
        .enumerate()
        .filter(|(i, s)| i % 2 == 1 && !s.is_empty())
        .map(|(_, s)| s.to_string())
        .collect()
}

/// decode rust string-literal escapes; real newlines in the multi-line consts
/// pass through untouched
fn unescape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut it = s.chars();
    while let Some(c) = it.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match it.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some(o) => out.push(o),
            None => out.push('\\'),
        }
    }
    out
}

/// json-encode a string for embedding in the generated ts (no serde in build deps)
fn json_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

// packages/api/src/api.gen.ts

/// first char uppercased, the command names are single words, so the options
/// interface is `{ts_type(&name)}Options` and the builder `{name}Argv`
fn camel(name: &str) -> String {
    let mut c = name.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}

/// kebab-case command name → ts identifier: "set-version" → "setVersion"
/// (the argv literal keeps the real name; only identifiers camelCase)
fn ts_ident(name: &str) -> String {
    name.split('-')
        .enumerate()
        .map(|(i, p)| if i == 0 { p.to_string() } else { camel(p) })
        .collect()
}

/// kebab-case → PascalCase, for the Options interface name ("set-version" → "SetVersion")
fn ts_type(name: &str) -> String {
    name.split('-').map(camel).collect()
}

/// "--frozen-lockfile" → "frozenLockfile"
fn field_name(flag: &str) -> String {
    let kebab = flag.trim_start_matches('-');
    let mut out = String::new();
    for (i, part) in kebab.split('-').enumerate() {
        if i == 0 {
            out.push_str(part);
        } else {
            out.push_str(&camel(part));
        }
    }
    out
}

/// keep `*/` out of generated jsdoc text
fn sanitize(s: &str) -> String {
    s.replace("*/", "* /")
}

/// the generated api surface: per-command jsdoc'd options interfaces, argv
/// builders (so option → flag mapping can't drift from zap's real parsers)
/// and the ZapApi interface. the zapApi implementation lives in index.ts,
/// typed against ZapApi, a spec/registry mismatch fails typecheck there
fn gen_api_ts(groups: &[(String, Vec<String>)], cmds_dir: &Path) -> String {
    let mut out = String::from(
        "// generated by build.rs from src/api_spec.rs + the src/cmds tree, do not edit by hand\n\n",
    );
    out.push_str("import type { RunResult, LsJson, WhyJson, ViewJson, OutdatedJson, InstallJson, WithData } from '../index';\n\n");

    let mut interface = String::new();
    for (group, cmds) in groups {
        for c in cmds {
            let path = cmds_dir.join(group).join(format!("{c}.rs"));
            let src = fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {}", path.display(), e));
            let name = str_const(&src, "NAME").unwrap_or_else(|| c.clone());
            let spec = api_spec::SPECS
                .iter()
                .find(|s| s.name == name)
                .unwrap_or_else(|| panic!("api_spec.rs: no spec for command `{}` (add one)", name));
            let ts = ts_ident(&name);
            let ty = ts_type(&name);

            // jsdoc'd options interface, only when the command parses flags
            if !spec.options.is_empty() {
                out.push_str(&format!("export interface {ty}Options {{\n"));
                for o in spec.options {
                    let short = match o.short {
                        Some(s) => format!(" ({s})"),
                        None => String::new(),
                    };
                    out.push_str(&format!("  /** {}{} */\n", sanitize(o.desc), short));
                    let kind = match o.kind {
                        api_spec::OptKind::Bool => "boolean",
                        api_spec::OptKind::Str => "string",
                        api_spec::OptKind::StrList => "string[]",
                    };
                    out.push_str(&format!("  {}?: {};\n", field_name(o.flag), kind));
                }
                out.push_str("}\n\n");
            }

            // argv builder: positionals in spec order, then the flags
            let mut pos_params: Vec<String> = Vec::new();
            let mut argv: Vec<String> = Vec::new();
            for p in spec.positionals {
                match (p.kind, p.optional, p.via_sep) {
                    (api_spec::PosKind::Str, false, _) => {
                        pos_params.push(format!("{}: string", p.name));
                        argv.push(p.name.to_string());
                    }
                    (api_spec::PosKind::Str, true, _) => {
                        pos_params.push(format!("{}?: string", p.name));
                        argv.push(format!("...({} ? [{}] : [])", p.name, p.name));
                    }
                    (api_spec::PosKind::StrList, false, false) => {
                        pos_params.push(format!("{}: string[]", p.name));
                        argv.push(format!("...{}", p.name));
                    }
                    (api_spec::PosKind::StrList, _, false) => {
                        pos_params.push(format!("{}?: string[]", p.name));
                        argv.push(format!("...({} ?? [])", p.name));
                    }
                    (api_spec::PosKind::StrList, _, true) => {
                        pos_params.push(format!("{}?: string[]", p.name));
                        argv.push(format!("...({}?.length ? [\"--\", ...{}] : [])", p.name, p.name));
                    }
                }
            }
            let opts_param = if spec.options.is_empty() { None } else { Some(format!("o?: {ty}Options")) };
            let mut params = pos_params.clone();
            if let Some(p) = &opts_param {
                params.push(p.clone());
            }
            for o in spec.options {
                let f = field_name(o.flag);
                argv.push(match o.kind {
                    api_spec::OptKind::Bool => format!("...((o?.{f}) ? [\"{}\"] : [])", o.flag),
                    api_spec::OptKind::Str => format!("...((o?.{f}) ? [\"{}\", o.{f}] : [])", o.flag),
                    api_spec::OptKind::StrList => format!("...((o?.{f}?.length) ? [\"{}\", ...o.{f}] : [])", o.flag),
                });
            }
            let argv_body = if argv.is_empty() {
                json_str(&name)
            } else {
                format!("{}, {}", json_str(&name), argv.join(", "))
            };
            out.push_str(&format!(
                "export function {ts}Argv({}): string[] {{\n  return [{argv_body}];\n}}\n\n",
                params.join(", "),
            ));

            // the ZapApi method: jsdoc from the registry's about + the spec
            let ret = if spec.returns == "RunResult" {
                "Promise<RunResult>".to_string()
            } else {
                format!("Promise<WithData<{}>>", spec.returns)
            };
            interface.push_str("  /**\n");
            for line in str_const(&src, "ABOUT").unwrap_or_default().lines() {
                interface.push_str(&format!("   * {}\n", sanitize(line)));
            }
            for p in spec.positionals {
                interface.push_str(&format!("   * @param {} - {}\n", p.name, sanitize(p.desc)));
            }
            for o in spec.options {
                interface.push_str(&format!(
                    "   * @param options.{} - {}\n",
                    field_name(o.flag),
                    sanitize(o.desc)
                ));
            }
            interface.push_str("   *\n   * @example\n");
            for line in str_const(&src, "EXAMPLE").unwrap_or_default().lines() {
                interface.push_str(&format!("   *   {}\n", sanitize(line)));
            }
            interface.push_str("   */\n");
            let mut sig_params = pos_params.clone();
            if !spec.options.is_empty() {
                sig_params.push(format!("options?: {ty}Options"));
            }
            interface.push_str(&format!("  {}({}): {};\n\n", ts, sig_params.join(", "), ret));
        }
    }

    out.push_str("export interface ZapApi {\n");
    out.push_str(&interface);
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::{json_str, replace_version};

    #[test]
    fn version_sync_is_a_targeted_replace() {
        let pkg = "{\n  \"name\": \"@zappkg/cli\",\n  \"version\": \"0.1.0\",\n  \"deps\": {\n    \"tar\": \"^7.4.3\"\n  }\n}\n";
        let want = pkg.replace("\"0.1.0\"", "\"9.9.9\"");
        assert_eq!(replace_version(pkg, "9.9.9").unwrap(), want);
        // already in sync → None; field absent → None
        assert_eq!(replace_version(pkg, "0.1.0"), None);
        assert_eq!(replace_version("{\"name\":\"x\"}", "1.0.0"), None);
    }

    #[test]
    fn json_str_escapes_like_json() {
        assert_eq!(json_str("a\"b\\c\nd\te"), "\"a\\\"b\\\\c\\nd\\te\"");
    }
}
