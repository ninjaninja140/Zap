// `zap skills [--remove]`, inject/update the zap usage block into
// CLAUDE.md or AGENTS.md so AI assistants understand the zap mental model

use anyhow::Result;
use std::path::PathBuf;

use crate::cmds::{has_zap_block, inject_skills, strip_skills};
use crate::util::{dim, green};

pub const NAME: &str = "skills";
pub const ALIASES: &[&str] = &[];
pub const USAGE: &str = "inject zap usage into CLAUDE.md / AGENTS.md (--remove to strip)";

const SKILLS_BLOCK: &str = r#"## zap package manager

This project uses **zap**, not npm/yarn/pnpm/bun. There is no `node_modules`, a custom PnP runtime (`.pnp.cjs`) resolves packages at runtime.

### Commands
- Install: `zap install`, **never** `npm install` (corrupts the PnP runtime)
- Add dep: `zap add <pkg>` or `zap add --dev <pkg>`
- Remove dep: `zap remove <pkg>`
- Run script: `zap run <script>` / `zap r <script>` / `zap <script>`
- Execute: `zap exec <cmd>`, injects the PnP runtime into the process tree
- Run binary: `zap x <bin>`, local first, npx-style fallback
- Scaffold: `zap create <template>` (like npm create)
- TypeScript: `zap tsc` (built-in, version pinned in `.zaprc`)
- Migrate: `zap migrate --dry-run` (from npm/yarn/pnpm/bun/deno)

### Diagnostics
- `zap doctor`, sanity checks
- `zap why --project <pkg>`, find source file references to a package
- `zap outdated`, check for outdated deps
- `zap audit`, check for known vulnerabilities
- `zap view <pkg>`, registry metadata

### Config
- `.zaprc.yaml` etc. in project root or any parent (walks up)
- `zap config <key> <value>` to set, `zap config` to dump, `zap config <key>` to read one
- Keys: linker (pnp|node-modules), registry, typescript, concurrency, strict, save-exact, prefer-offline, cache-ttl, lifecycle, store-dir, token, editor-node-modules
- Global: `zap config -g <key> <value>` (stored in ~/.zap/config.yaml)

### Registries
- `zap registry add <name> <url>` / `zap registry use <name>` / `zap registry current`
- `zap publish` speaks the npm publish protocol
- `zap login` / `zap whoami` for auth

### Rules
- Never edit `.zap/`, regenerated by `zap install`
- Never run `npm install` / `yarn install` / `pnpm install` / `bun install`, corrupts the PnP runtime
- `.zap-lock.json` is the lockfile, commit it
- `zap exec` and `zap run` inject the PnP runtime into the process tree
- On Linux/macOS the same commands work (rustls TLS, no openssl needed)
"#;

pub fn run(args: &[String]) -> Result<i32> {
    let cwd = std::env::current_dir()?;
    let remove = args.iter().any(|a| a == "--remove");
    let candidates = [cwd.join("CLAUDE.md"), cwd.join("AGENTS.md")];
    let mut target: Option<PathBuf> = None;

    for path in &candidates {
        if let Ok(content) = std::fs::read_to_string(path) {
            if has_zap_block(&content) {
                target = Some(path.clone());
                break;
            }
        }
    }

    if target.is_none() {
        for path in &candidates {
            if path.is_file() {
                target = Some(path.clone());
                break;
            }
        }
    }

    let target = target.unwrap_or_else(|| candidates[1].clone());
    let block = format!("{}\n{}\n{}", crate::cmds::SKILLS_START, SKILLS_BLOCK, crate::cmds::SKILLS_END);

    if remove {
        if strip_skills(&target)? {
            println!("{} zap block removed from {}", green("-"), target.display());
        } else {
            println!("{}", dim("no zap block found"));
        }
        return Ok(0);
    }

    let had_block = std::fs::read_to_string(&target)
        .map(|c| has_zap_block(&c))
        .unwrap_or(false);

    inject_skills(&target, &block)?;

    if had_block {
        println!("{} zap block updated in {}", green("↻"), target.display());
    } else {
        println!("{} zap instructions injected into {}", green("+"), target.display());
    }
    
    Ok(0)
}
